// Emits prisma/schema.postgres.prisma from the canonical SQLite schema so the
// two never drift: identical models, only the datasource block differs.
// Used by scripts/vercel-build.sh (Vercel) — local dev keeps SQLite.
const fs = require("fs");
const path = require("path");
const src = path.join(__dirname, "..", "prisma", "schema.prisma");
const out = path.join(__dirname, "..", "prisma", "schema.postgres.prisma");
let schema = fs.readFileSync(src, "utf8");
const before = schema;
schema = schema.replace(
  /datasource db \{\s*provider\s*=\s*"sqlite"\s*url\s*=\s*env\("DATABASE_URL"\)\s*\}/,
  'datasource db {\n  provider  = "postgresql"\n  url       = env("DATABASE_URL")\n  directUrl = env("DATABASE_URL_UNPOOLED")\n}',
);
if (schema === before) {
  console.error("make-postgres-schema: could not find the sqlite datasource block in prisma/schema.prisma");
  process.exit(1);
}
schema = `// GENERATED by scripts/make-postgres-schema.js — do not edit. Edit prisma/schema.prisma.\n${schema}`;
fs.writeFileSync(out, schema);
console.log(`wrote ${path.relative(process.cwd(), out)}`);
