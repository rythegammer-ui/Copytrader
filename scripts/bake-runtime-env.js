// Inline runtime configuration into the server bundle via next.config `env`.
//
// For hosts where environment variables cannot be set on the project (for
// example an API-only bootstrap deployment): run this in the INSTALL step with
// the values in this process's environment, and Next.js replaces
// process.env.<KEY> in server code with the literal at build time.
// Only server-only keys are baked. Never bake anything a client component
// references — those would be inlined into public JavaScript too.
// Regenerates next.config.mjs; do not commit the result.
const fs = require("fs");
const path = require("path");

const KEYS = [
  "DATABASE_URL",
  "SESSION_SECRET",
  "TAX_RATE_BPS",
  "STRIPE_SECRET_KEY",
  "STRIPE_WEBHOOK_SECRET",
  "RESEND_API_KEY",
  "MAIL_FROM",
  "PUBLIC_BASE_URL",
];
const env = {};
for (const k of KEYS) if (process.env[k]) env[k] = process.env[k];
if (!env.DATABASE_URL || !env.SESSION_SECRET) {
  console.error("bake-runtime-env: DATABASE_URL and SESSION_SECRET are required in the environment");
  process.exit(1);
}
const config = `/** @type {import('next').NextConfig} */
// GENERATED by scripts/bake-runtime-env.js at build time — do not commit.
const nextConfig = {
  reactStrictMode: true,
  env: ${JSON.stringify(env, null, 2)},
};

export default nextConfig;
`;
fs.writeFileSync(path.join(__dirname, "..", "next.config.mjs"), config);
console.log(`bake-runtime-env: inlined ${Object.keys(env).join(", ")} into next.config.mjs`);
